def main():
    shutil.copy2(SRC, OUT)
    doc = Document(OUT)
    applied = []

    for marker, parts, note in REWRITES:
        for paragraph in doc.paragraphs:
            text = paragraph.text
            if text.startswith(marker):
                add_parts(paragraph, parts)
                applied.append((marker, note))
                break
        else:
            raise RuntimeError(f"未找到目标段落：{marker}")

    doc.save(OUT)

    text = "\n".join(p.text for p in doc.paragraphs)
    body = text.split("参考文献", 1)[0]
    cited = set()
    for match in re.findall(r"\[([0-9,\-]+)\]", body):
        for part in match.split(","):
            if "-" in part:
                a, b = part.split("-", 1)
                cited.update(range(int(a), int(b) + 1))
            elif part:
                cited.add(int(part))
    missing = [i for i in range(1, 51) if i not in cited]

    lines = [
        "# 参考文献正文交叉引用说明",
        "",
        f"源文件：{SRC.name}",
        f"输出文件：{OUT.name}",
        "",
        "## 已处理位置",
        "",
    ]
    for _, note in applied:
        lines.append(f"- {note}")
    lines.extend([
        "",
        "## 覆盖检查",
        "",
        f"- 正文已覆盖参考文献编号：{min(cited)}-{max(cited)}，共 {len(cited)} 条。",
        f"- 未在正文出现的编号：{missing if missing else '无'}。",
        "",
        "## 引用分组逻辑",
        "",
        "- [1-7]：煤矿智能化、绿色开采、智能化开采综述与技术体系。",
        "- [8-10,40-42]：透明工作面、三维地质建模、数字孪生与多源地质建模。",
        "- [11-21]：覆岩移动、采动应力、沉陷和裂隙演化。",
        "- [22-33,46-50]：导水裂隙、含水层保护、保水采煤和地下水库。",
        "- [34-39]：采区/矿山方案优化、多目标优化和方案比选。",
        "- [37,40]：生产接续、智能开采流程和开采组织。",
        "- [43-45]：经济评价、现金流和不确定性分析。",
    ])
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(OUT)
    print(REPORT)
    print("missing", missing)


if __name__ == "__main__":
    main()
