def main() -> int:
    if len(sys.argv) != 2:
        print("Usage: embed_chinese_citations_20260418.py <docx>")
        return 2
    path = Path(sys.argv[1])
    doc = Document(str(path))
    for idx, text in REPLACEMENTS.items():
        doc.paragraphs[idx].text = text
    doc.save(str(path))
    with zipfile.ZipFile(path) as zf:
        bad = zf.testzip()
    if bad is not None:
        raise RuntimeError(f"Bad DOCX zip member: {bad}")

    ref_idx = next(i for i, p in enumerate(doc.paragraphs) if p.text.strip() == "参考文献")
    body = "\n".join(p.text for p in doc.paragraphs[:ref_idx])
    refs = sorted(int(m.group(1)) for m in re.finditer(r"^\[(\d+)\]", "\n".join(p.text for p in doc.paragraphs), re.M))
    used = set()
    for m in re.finditer(r"\[([0-9 ,，\-－–—]+)\]", body):
        raw = m.group(1)
        nums = [int(x) for x in re.findall(r"\d+", raw)]
        if re.search(r"[\-－–—]", raw) and len(nums) == 2 and 1 <= nums[0] <= nums[1] <= 50:
            used.update(range(nums[0], nums[1] + 1))
        else:
            used.update(n for n in nums if 1 <= n <= 50)
    print(path)
    print("refs", len(refs), min(refs), max(refs))
    print("used_body", sorted(used))
    print("unused_body", [n for n in refs if n not in used])
    print("missing_referenced", [n for n in used if n not in refs])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
